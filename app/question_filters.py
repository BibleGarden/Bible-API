"""Post-filters for the leading question: gender, menus, tails.

ClickUp 86cbejvra (umbrella 86cbejvq1), from the independent assessment in
`evaluation/bench_data/question_comparison_prompt_v5_before_after/FABLE_ASSESSMENT.md`:
prompt wording did not fix three defects of Qwen3-30B, and the assessment's own
recommendation was to stop asking the model and to decide them in code.

* **Gender.** Prompt v5 says «do not default to the masculine» and Qwen obeys it
  *worse* than v4 did: 15 masculine addresses to a woman against 1. The person
  usually says their gender in their own first words («я рада», «заснула»,
  «втомилася»), so `detect_gender` reads it there and `gender_mismatch` says
  whether a candidate question addresses the other gender.
* **Menus.** «X или Y?» hands the person a closed choice instead of a question.
* **Tails.** «… — как ты будешь узнавать это?» is the shape the journal loop
  took: the same sentence with a new ending.

**Nothing here is wired into `app/twinkler_ai.py`.** This module is the
measurement instrument of 86cbejvra; whether the endpoint regenerates on a
verdict is a separate decision with its own ticket.

Dependency-free like `question_prompt.py` and `question_novelty.py`: the
standard library only, so the evaluation tools and the tests import it without
the application, and no environment variable can move any constant (ADR 0008).

## The constants

| constant | value | what it decides |
| --- | --- | --- |
| `FEMININE_SELF` / `MASCULINE_SELF` | 48 + 48 forms | which of the person's own words name their gender |
| `FEMININE_ADDRESS` / `MASCULINE_ADDRESS` | 47 + 52 forms | which forms in a question address a gendered «ты» |
| `AMBIGUOUS_ADDRESS` | `сам сама один одна` | address forms that also live as ordinary words («один день»), so they need a pronoun beside them |
| `ADDRESS_LOOKBACK` | 7 | how far back a gendered form looks for the second-person marker it belongs to |
| `AMBIGUOUS_LOOKBACK` | 2 | … for those four, where a distant pronoun is a measured false positive |
| `ADDRESS_LOOKAHEAD` | 2 | … and forward, for «услышала ли ты» word order |
| `MENU_CONJUNCTIONS` | `или чи or` | the conjunction a menu is built on |
| `MENU_MIN_SIDE_WORDS` | 2 | words each alternative needs, so «или» inside one phrase is not a menu |
| `TAIL_MIN_WORDS` | 3 | words after a dash that make it an appended clause rather than an aside |

Every list is **reviewed**, never generated by a rule like "words ending in
`-ла`". The reason is in the data: `series-exhaustion-uk` has the person write
«заснула» about herself and «колега звільнився» about someone else in the same
two sentences, and `gratitude-ru` has «сосед помог». A morphological rule reads
those as the person's own gender and gets both inputs wrong; a reviewed list
simply does not contain «звільнився» or «помог».

## What each function is, and is not

`detect_gender` is evidence about the person, not a claim about their identity:
it answers `None` whenever their words disagree or say nothing, and `None` is
the ordinary case (5 of the 16 benchmark inputs, plus every English one — the
language has no such forms and the lists carry none).

`gender_mismatch` at `gender=None` flags **any** explicit gendered address:
with no evidence, a gendered form is a gender the model imposed. That is the
column the assessment counts as «род навязан при неизвестном».

`is_menu` and `has_tail` are heuristics with **known false positives**, and are
meant for counting a corpus, not for rejecting one answer on their own:

* `is_menu` cannot tell «X или Y?» from «пять или шесть минут» or from a
  Ukrainian «чи» meaning "whether". Measured on the 396 benchmark answers it
  agrees with the manual count where the manual count exists; the disagreements
  are listed in `evaluation/README.md`, section «Промпт наводящего вопроса
  v6-A».
* `has_tail` counts every dash with a clause after it, including the ones that
  carry the whole point of the question («что именно — в деталях, в ритме —
  делает…»). It measures a shape, not a defect.

## Measured against the manual count

`tests/test_question_filters.py` runs this module over all 396 answers of the
four benchmark artifacts (Qwen and Gemini, prompts v4 and v5) and pins the
numbers. Against the hand count in `FABLE_ASSESSMENT.md`, «Род и язык»:

| combination | manual (wrong gender + imposed) | this module | rows |
| --- | --- | --- | --- |
| Qwen / v4 | 1 + 3 | **1 + 3** | the same rows |
| Qwen / v5 | 15 + 4 | **15 + 4** | the same rows |
| Gemini / v4 | 0 + 2 | 1 + 2 | one extra, below |
| Gemini / v5 | 0 + 0 | **0 + 0** | — |

The single disagreement is `series-gratitude-ru` sample 2 step 4 of Gemini/v4,
«Что ты чувствовала, когда отчёт **был наконец готов**?»: «готов» is a
masculine short adjective agreeing with «отчёт», six words after the «ты» that
the window rule attaches it to. It is a false positive of the window, not of
the list, and it is left in rather than tuned away — the alternative was a
narrower window that drops a real miss (`series-scale-ru` s2 st6 of Qwen/v5,
«даже если не уверен», also six words out), and tuning a rule until one corpus
comes out right is how a detector stops measuring anything.

**That row is one instance of a whole class, and the class is wider than a
short adjective.** `_addresses_the_person` attaches a gendered form to the
nearest *pronoun*; a third-person **noun** subject standing between the
pronoun and the form is invisible to it, because nothing here does morphology.
So every sentence of the shape "«ты» … <noun> <gendered verb>" is flagged:

* «Что ты почувствовала, когда **твой муж сказал** тебе об этом?» → `{f, m}`
* «Что ты почувствовала, когда **малыш заснул** у тебя на руках?» → `{f, m}`
* «Что ты чувствовала, когда **отчёт был** наконец готов?» → `{f, m}`

Only a third-person *pronoun* stops the scan («что **он** хотел» is correctly
ignored). The class costs one row in 396 here, and it is a floor on how far
this heuristic can be trusted: a verdict of "wrong gender" on a single answer
must be read, not acted on, and a genuine fix is morphological agreement,
which this module deliberately does not attempt.
"""

from __future__ import annotations

