# «сам», «сама», «один», «одна» are also ordinary words — «на один день», «сама
# по себе мысль». They count only with a second-person pronoun beside them.
AMBIGUOUS_ADDRESS = frozenset({"сам", "сама", "один", "одна"})

# Whom a gendered form belongs to is decided by the nearest second-person
# marker. Seven words back covers «Что из завтрашних дел ты уже сейчас видишь
# как необходимое, даже если не уверен»; two forward cover the inverted
# «услышала ли ты». The ambiguous four get a much tighter window — see below.
ADDRESS_LOOKBACK = 7
ADDRESS_LOOKAHEAD = 2
AMBIGUOUS_LOOKBACK = 2
_SECOND_PERSON = frozenset({
    "ты", "тебя", "тебе", "тобой", "тобою", "твой", "твоя", "твое",
    "твои", "твоим", "твоей", "твоего", "твоих",
    "ти", "тобі", "твій", "твоє", "твої", "твоїм", "твоєї",
})
_THIRD_PERSON = frozenset({
    "он", "она", "оно", "они", "его", "ее", "их", "ней", "нее", "него",
    "них", "нею", "ним", "ними",
    "він", "вона", "воно", "вони", "його", "її", "їх", "їм", "ними",
})
# A second-person singular verb is a second-person marker too, and it is the
# only one many questions carry: «Що відчуваєш, коли … що хотів зробити».
# A suffix rule rather than a list, because the verb itself is unbounded.
#
# The length floor is where the rule stops, and it is a trade measured rather
# than assumed. At 6 the nouns that end the same way are out of reach — «тишь»,
# uk «миш», and «малыш», which at 5 makes «Малыш заснул, а что осталось с
# тобой?» look like an address. The price is that the genuine five-letter
# second-person verbs stop being markers: «хочеш», «можеш», «робиш», «бачиш»,
# «кажеш», «мрієш», «ждешь», «идешь» — all eight occur in the benchmark
# answers. Neither side of the trade moves a single verdict on the 846 measured
# answers (396 of the four comparison artifacts + 450 of the six sampling runs
# of 86cbejvra), because a question carrying one of those verbs carries a
# second-person pronoun too; so the floor decides the rule's reach, not this
# corpus, and 6 is the conservative end of it.
#
# It does NOT close the false-positive class of `_addresses_the_person` below:
# «Что ты почувствовала, когда малыш заснул…» is flagged at either floor,
# because «ты» is the marker there.
_SECOND_PERSON_VERB = re.compile(
    r"(?:ешь|ишь|ешься|ишься|єш|еш|иш|їш|єшся|ешся|ишся|їшся)$"
)
_MIN_VERB_LENGTH = 6


def _is_second_person(token: str) -> bool:
    return token in _SECOND_PERSON or (
        len(token) >= _MIN_VERB_LENGTH and bool(_SECOND_PERSON_VERB.search(token))
    )


def _addresses_the_person(tokens: Sequence[str], index: int) -> bool:
    """Is the gendered form at `index` addressed to the person?

    The nearest marker decides. A second-person one first — «ты … сделала»,
    «відчуваєш … хотів» — means the form is an address; a third-person pronoun
    first — «что он хотел» — means it is about somebody else and this module
    says nothing about it. With no marker in the window the form is not
    counted: counting a bare participle would flag «какой была эта тишина».

    **A third-person NOUN subject does not stop the scan** — «когда твой муж
    сказал», «когда малыш заснул», «когда отчёт был готов» all read as
    addresses. That is the documented false-positive class of this module (see
    the docstring); closing it needs morphological agreement, not a narrower
    window — a narrower window loses real findings at the same distance.

    `AMBIGUOUS_ADDRESS` («сам», «одна», …) uses `AMBIGUOUS_LOOKBACK` instead,
    and the reason is a measured false positive: «важно для тебя — не просто
    результат, а сам акт делать» has «тебя» five words before a «сам» that
    means "the act itself". Those four words are an address only when the
    pronoun is next to them («ты сам», «ты не одна»).
    """
    lookback = (
        AMBIGUOUS_LOOKBACK if tokens[index] in AMBIGUOUS_ADDRESS else ADDRESS_LOOKBACK
    )
    for step in range(1, lookback + 1):
        position = index - step
        if position < 0:
            break
        if _is_second_person(tokens[position]):
            return True
        if tokens[position] in _THIRD_PERSON:
            return False
    for step in range(1, ADDRESS_LOOKAHEAD + 1):
        position = index + step
        if position >= len(tokens):
            break
        if _is_second_person(tokens[position]):
            return True
        if tokens[position] in _THIRD_PERSON:
            return False
    return False


def addressed_genders(question: str) -> set[str]:
    """Which genders this question addresses the person in — `f`, `m`, both."""
    tokens = words(question)
    found: set[str] = set()
    for index, token in enumerate(tokens):
        feminine = token in FEMININE_ADDRESS
        masculine = token in MASCULINE_ADDRESS
        if not feminine and not masculine:
            continue
        # `AMBIGUOUS_ADDRESS` needs the pronoun for a different reason than the
        # rest — «один день» is not an address at all — but the same test
        # answers both, so there is one call and one rule.
        if not _addresses_the_person(tokens, index):
            continue
        # A form that is feminine in one language and masculine in the other
        # would be undecidable; there is none in the lists, and a future one
        # would show up as "both" rather than as a silent choice.
        if feminine:
            found.add(FEMININE)
        if masculine:
            found.add(MASCULINE)
    return found


def gender_mismatch(question: str, gender: str | None) -> bool:
    """Does this question address the person as the wrong gender?

    With a known `gender`, a mismatch is an address in the other one. With
    `gender is None` — the person's words say nothing — **any** explicit
    gendered address is a mismatch: the model imposed a gender the request did
    not carry, and half the time it will be wrong.
    """
    addressed = addressed_genders(question)
    if not addressed:
        return False
    if gender is None:
        return True
    return any(other != gender for other in addressed)


# --- 3. a menu instead of a question ---------------------------------------
MENU_CONJUNCTIONS = frozenset({"или", "чи", "or"})
MENU_MIN_SIDE_WORDS = 2


def is_menu(question: str) -> bool:
    """Does this question offer a closed choice — «X или Y?»

    Heuristic, and it says so: a conjunction that is not the first words of the
    question and has at least `MENU_MIN_SIDE_WORDS` words on either side. That
    catches «то, что вы смеялись, или то, что вы снова оказались рядом?» and
    misses nothing the assessment counted by hand — but it also cannot tell an
    alternative from «пять или шесть минут», from a Ukrainian «чи» meaning
    "whether", or from an English «or» inside one noun phrase. False positives
    are acceptable for counting a corpus and are the reason this verdict is not
    a rejection on its own.
    """
    tokens = words(question)
    for index, token in enumerate(tokens):
        if token not in MENU_CONJUNCTIONS:
            continue
        if index >= MENU_MIN_SIDE_WORDS and (
            len(tokens) - index - 1 >= MENU_MIN_SIDE_WORDS
        ):
            return True
    return False


# --- 4. an appended tail ---------------------------------------------------
TAIL_MIN_WORDS = 3
# A dash with spaces on both sides — em, en or plain hyphen. A hyphen inside a
# word («что-то») has no spaces and is not one.
_DASH = re.compile(r"\s[—–-]\s")
# «не просто X, а Y» and its two siblings: the same appended clause built out of
# words instead of punctuation.
_NOT_JUST = (
    re.compile(r"\bне\s+просто\b.{1,200}?\bа\b", re.IGNORECASE | re.DOTALL),
    re.compile(r"\bне\s+лише\b.{1,200}?\bа\b", re.IGNORECASE | re.DOTALL),
    re.compile(r"\bnot\s+just\b.{1,200}?\bbut\b", re.IGNORECASE | re.DOTALL),
)


def has_tail(question: str) -> bool:
    """Is a clause appended to this question after a dash — or a «не просто … а …»?

    The shape the journal loop took: one sentence reused with a new ending. A
    dash counts only when at least `TAIL_MIN_WORDS` words follow it, so a
    parenthetical dash pair in the middle («что именно — в деталях — делает»)
    is judged by what comes after the LAST dash, and a trailing «— как?» is not
    a tail either.

    This counts a shape, not a defect: the dash frequently carries the point of
    the question. Read the number, do not act on one verdict.
    """
    for match in _DASH.finditer(question):
        if len(words(question[match.end():])) >= TAIL_MIN_WORDS:
            return True
    return any(pattern.search(question) for pattern in _NOT_JUST)
