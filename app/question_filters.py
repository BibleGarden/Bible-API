FEMININE = "f"
MASCULINE = "m"


def detect_gender(person_texts: Sequence[str]) -> str | None:
    """The person's grammatical gender from their own words, or `None`.

    `person_texts` is what the person wrote: the topic of the prayer and their
    `user` turns. English text says nothing (the lists hold no English), and
    neither does a person who simply did not use a gendered form — both answer
    `None`, which is the ordinary case rather than a failure.

    Words of **both** genders answer `None` as well: one of them is about
    somebody else, and there is no way to tell which, so a request that carries
    a contradiction is treated as carrying no evidence.
    """
    feminine = masculine = False
    for text in person_texts:
        for word in words(text):
            if word in FEMININE_SELF:
                feminine = True
            elif word in MASCULINE_SELF:
                masculine = True
    if feminine == masculine:  # both, or neither
        return None
    return FEMININE if feminine else MASCULINE


