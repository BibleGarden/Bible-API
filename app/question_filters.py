# --- tokenisation ----------------------------------------------------------
# The same normalisation `question_novelty` uses, kept local rather than
# imported: these two modules answer different questions and neither should
# start depending on the other's spelling rules. Casefold, ё→е (Russian spells
# the same word both ways), everything that is not a word character or space
# becomes a space. Ukrainian `і`, `ї`, `є`, `ґ` are word characters and survive;
# the apostrophe of «сім'ю» is not, so that word splits — harmless here, since
# no list below contains an apostrophe.
_NON_WORD = re.compile(r"[^\w\s]", re.UNICODE)


def words(text: str) -> list[str]:
    """The text as normalized word tokens."""
    return _NON_WORD.sub(" ", text.casefold().replace("ё", "е")).split()


